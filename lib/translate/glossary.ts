/**
 * Curated Persian equivalents, used before any machine translation.
 *
 * - Titles: the established titles of Persian editions of well-known books
 *   (e.g. Dune → «تلماسه», not a literal "sand dune").
 * - Names: conventional Persian spellings of well-known authors.
 * - Subjects: common Open Library subject headings.
 *
 * Keys are normalized with `glossaryKey()`.
 */

export function glossaryKey(text: string): string {
  return text
    .normalize("NFKC")
    .toLocaleLowerCase("en")
    .replace(/[“”«»"]/g, "")
    .replace(/[’‘`]/g, "'")
    .replace(/\[[^\]]*\]/g, " ") // "[12 stories]"
    .replace(/^[.\s…]+/, "") // "... Trotzdem"
    .replace(/[\s.,;:!?]+$/, "")
    .replace(/\s+/g, " ")
    .trim();
}

function normalizeKeys(entries: Record<string, string>): ReadonlyMap<string, string> {
  return new Map(Object.entries(entries).map(([k, v]) => [glossaryKey(k), v]));
}

