export type GlossaryKind = "title" | "name" | "subject";

/** Returns a curated translation, or null when the glossary has no entry. */
export function lookupGlossary(text: string, kind: GlossaryKind): string | null {
  const key = glossaryKey(text);
  if (!key) return null;
  if (kind === "title") return TITLE_GLOSSARY.get(key) ?? null;
  if (kind === "name") return NAME_GLOSSARY.get(key) ?? null;

  const direct = SUBJECT_GLOSSARY.get(key);
  if (direct) return direct;
  // "Fiction, science fiction, general" → "داستان، علمی‌تخیلی، عمومی"
  const parts = key.split(/\s*[,/]\s*|\s+--\s+/).filter(Boolean);
  if (parts.length < 2) return null;
  const translated = parts.map((p) => SUBJECT_GLOSSARY.get(p));
  return translated.every(Boolean) ? Array.from(new Set(translated)).join("، ") : null;
}
